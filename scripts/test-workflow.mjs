import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const load=async(file)=>import('data:text/javascript;base64,'+Buffer.from(ts.transpileModule(fs.readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText).toString('base64'));
const {reportApp,completedStage}=await load('src/report/labels.ts');
const {lunchOverdue}=await load('src/lib/lunch.ts');
for(const name of ['Windows Shell Experience Host','Calculator','CapCut','Windows Explorer']) assert.equal(reportApp({app:name,category:'dis',minutes:5}).category,'prod');
assert.equal(reportApp({app:'Windows Explorer',category:'pausa',minutes:60}).category,'pausa');
assert.equal(reportApp({app:'Sala 8-bit',category:'com',minutes:23}),null);
assert.equal(reportApp({app:'wwm',category:'dis',minutes:5}).category,'dis');
assert.equal(completedStage({kind:'etapa',text:'Concluiu a etapa e passou para captacao'}),'Roteiro');
assert.equal(completedStage({kind:'etapa',text:'Concluiu a etapa e passou para edicao'}),'Captação');
assert.equal(completedStage({kind:'etapa',text:'Concluiu a etapa e passou para finalizacao'}),'Edição');
assert.equal(completedStage({kind:'concluiu',text:'Concluiu a tarefa',completed_stage:'finalizacao'}),'Finalização');
assert.equal(lunchOverdue('almoco',0,3599999),false);
assert.equal(lunchOverdue('almoco',0,3600000),true);
assert.equal(lunchOverdue('trabalhando',0,7200000),false);
assert.equal(lunchOverdue('almoco',NaN,7200000),false);
console.log('15 verificações: relatório, etapas e lembrete de almoço aprovados.');
